-- ------------------------------------------------------------
-- hints.page_path — страница, на которой живёт подсказка
--
-- До этого путь был только у версии тура (tour_versions.target_path),
-- то есть один на весь тур: модель описывала только одностраничный
-- сценарий. Шаг не мог сказать, что он ждёт элемент на другой странице,
-- и рантайм не знал, куда переходить.
--
-- Пустая строка означает «та же страница, где тур стартовал», то есть
-- наследование target_path. Значение по умолчанию выбрано именно таким,
-- чтобы уже существующие туры сохранили текущее поведение: без него
-- каждая старая подсказка получила бы конкретный путь, которого автор
-- не задавал.
-- ------------------------------------------------------------

ALTER TABLE hints ADD COLUMN page_path TEXT NOT NULL DEFAULT '';
